function priceHistory(baseline: number, days = 30): PricePoint[] {
  const now = Date.now()
  const points: PricePoint[] = []
  let price = baseline + (Math.random() - 0.5) * 20
  for (let i = days; i >= 0; i--) {
    price = Math.max(2, Math.min(97, price + (Math.random() - 0.5) * 5))
    points.push({
      ts: now - i * 86_400_000,
      yes_price: Math.round(price),
      volume: Math.floor(Math.random() * 50000 + 5000),
    })
  }
  return points
}

